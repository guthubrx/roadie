/// Filtre de confidentialité strict du presse-papiers (Spec 163).
/// Tout contenu masqué, transitoire, auto-généré, issu d'un gestionnaire de mots de passe ou trop
/// volumineux est rejeté avant toute lecture/écriture sur disque.
public enum ClipboardSecurityFilter {
    /// Types NSPasteboard standards indiquant un secret ou une écriture transitoire (nspasteboard.org).
    public static let forbiddenPasteboardTypes: Set<String> = [
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.transientpasteboardtype",
        "pasteboard generator type",
    ]

    /// Plafond mémoire/disque par entrée (64 Kio UTF-8) pour préserver la réactivité.
    public static let maxStoredTextUTF8Bytes = 64 * 1024

    /// Retourne `true` si un type pasteboard interdit (secret, masqué, transitoire) est présent.
    public static func hasForbiddenPasteboardType(_ pasteboardTypes: Set<String>) -> Bool {
        for rawType in pasteboardTypes {
            if forbiddenPasteboardTypes.contains(rawType.lowercased()) {
                return true
            }
        }
        return false
    }

    /// Retourne `true` si la copie doit être ignorée. O(t + b).
    public static func shouldIgnore(
        text: String?,
        pasteboardTypes: Set<String>,
        sourceBundleID: String?,
        excludedBundles: [String]
    ) -> Bool {
        if hasForbiddenPasteboardType(pasteboardTypes) {
            return true
        }
        if let bundle = sourceBundleID?.trimmingCharacters(in: .whitespacesAndNewlines).lowercased(),
           !bundle.isEmpty {
            for excluded in excludedBundles {
                if excluded.trimmingCharacters(in: .whitespacesAndNewlines).lowercased() == bundle {
                    return true
                }
            }
        }
        guard let text else { return true }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return true }
        guard text.utf8.count <= maxStoredTextUTF8Bytes else { return true }
        return false
    }
}

/// Entrée locale de l'historique du presse-papiers (Spec 163).
public struct ClipboardHistoryEntry: Codable, Equatable, Sendable {
    public var id: String
    public var text: String
    public var copiedAt: Date
    public var sourceBundleID: String?
    public var pinned: Bool

    public init(
        id: String = UUID().uuidString.lowercased(),
        text: String,
        copiedAt: Date = Date(),
        sourceBundleID: String? = nil,
        pinned: Bool = false
    ) {
        self.id = id
        self.text = text
        self.copiedAt = copiedAt
        self.sourceBundleID = sourceBundleID
        self.pinned = pinned
    }

    /// Aperçu sur une ligne, borné en longueur pour le lanceur et la CLI.
    public func preview(maxLength: Int = 80) -> String {
        let singleLine = text
            .replacingOccurrences(of: "\r\n", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
            .replacingOccurrences(of: "\t", with: " ")
            .trimmingCharacters(in: .whitespaces)
        if singleLine.count <= maxLength { return singleLine }
        return String(singleLine.prefix(max(1, maxLength - 1))) + "…"
    }
}

/// Livre d'historique du presse-papiers : opérations pures (déduplication, épinglage, rétention, plafond).
public struct ClipboardHistoryBook: Codable, Equatable, Sendable {
    public var entries: [ClipboardHistoryEntry]

    public init(entries: [ClipboardHistoryEntry] = []) {
        self.entries = entries
    }

    /// Ajoute (ou remonte en tête) un texte, en conservant son état épinglé, puis purge les entrées expirées/en surplus.
    @discardableResult
    public mutating func record(
        text: String,
        sourceBundleID: String?,
        now: Date = Date(),
        maxItems: Int = 200,
        retentionDays: Int = 7
    ) -> ClipboardHistoryEntry {
        var preservedPin = false
        var preservedID: String?
        if let existingIdx = entries.firstIndex(where: { $0.text == text }) {
            preservedPin = entries[existingIdx].pinned
            preservedID = entries[existingIdx].id
            entries.remove(at: existingIdx)
        }
        let entry = ClipboardHistoryEntry(
            id: preservedID ?? UUID().uuidString.lowercased(),
            text: text,
            copiedAt: now,
            sourceBundleID: sourceBundleID,
            pinned: preservedPin
        )
        entries.insert(entry, at: 0)
        prune(now: now, maxItems: maxItems, retentionDays: retentionDays)
        return entry
    }

    /// Purge les entrées non épinglées expirées et applique la limite `maxItems` (en conservant les épinglées en priorité).
    public mutating func prune(now: Date = Date(), maxItems: Int = 200, retentionDays: Int = 7) {
        let limit = max(1, maxItems)
        let maxAge = TimeInterval(max(1, retentionDays)) * 86_400
        entries.removeAll { entry in
            !entry.pinned && now.timeIntervalSince(entry.copiedAt) > maxAge
        }
        if entries.count > limit {
            var remainingToDrop = entries.count - limit
            var idx = entries.count - 1
            while remainingToDrop > 0 && idx >= 0 {
                if !entries[idx].pinned {
                    entries.remove(at: idx)
                    remainingToDrop -= 1
                }
                idx -= 1
            }
            if entries.count > limit {
                entries.removeLast(entries.count - limit)
            }
        }
    }

    /// Recherche locale insensible à la casse/diacritiques ; les entrées épinglées remontent devant à égalité.
    public func search(_ query: String, limit: Int = 20) -> [ClipboardHistoryEntry] {
        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        let ordered = entries.sorted { lhs, rhs in
            if lhs.pinned != rhs.pinned { return lhs.pinned && !rhs.pinned }
            return lhs.copiedAt > rhs.copiedAt
        }
        guard !trimmed.isEmpty else { return Array(ordered.prefix(max(1, limit))) }
        let needle = LauncherMatch.fold(trimmed)
        let matches = ordered.filter { entry in
            LauncherMatch.fold(entry.text).contains(needle)
                || (entry.sourceBundleID.map { LauncherMatch.fold($0).contains(needle) } ?? false)
        }
        return Array(matches.prefix(max(1, limit)))
    }

    public func entry(matching idOrPrefix: String) -> ClipboardHistoryEntry? {
        let needle = idOrPrefix.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !needle.isEmpty else { return nil }
        if let exact = entries.first(where: { $0.id.lowercased() == needle }) {
            return exact
        }
        let prefixMatches = entries.filter { $0.id.lowercased().hasPrefix(needle) }
        return prefixMatches.count == 1 ? prefixMatches.first : nil
    }

    public mutating func togglePin(idOrPrefix: String) -> ClipboardHistoryEntry? {
        guard let target = entry(matching: idOrPrefix),
              let idx = entries.firstIndex(where: { $0.id == target.id })
        else { return nil }
        entries[idx].pinned.toggle()
        return entries[idx]
    }

    public mutating func delete(idOrPrefix: String) -> Bool {
        guard let target = entry(matching: idOrPrefix),
              let idx = entries.firstIndex(where: { $0.id == target.id })
        else { return false }
        entries.remove(at: idx)
        return true
    }

    /// Efface les entrées non épinglées (ou toutes avec `includePinned: true`). Retourne le nombre supprimé.
    @discardableResult
    public mutating func clear(includePinned: Bool) -> Int {
        let before = entries.count
        if includePinned {
            entries.removeAll()
        } else {
            entries.removeAll { !$0.pinned }
        }
        return before - entries.count
    }
}

/// Stockage local du presse-papiers avec écriture atomique POSIX `0o600` (Spec 163).
/// Aucune donnée en clair n'est jamais exposée avec des droits groupe/autres, même transitoirement.
public final class ClipboardHistoryStore: Sendable {
    public let url: URL

    public init(path: String? = nil) {
        let resolvedPath = path ?? TestEnvironment.launcherFile("clipboard.json")
        self.url = URL(fileURLWithPath: NSString(string: resolvedPath).expandingTildeInPath)
    }

    public func load() -> ClipboardHistoryBook {
        Self.decodeBook(from: url)
    }

    private static func decodeBook(from url: URL) -> ClipboardHistoryBook {
        guard let data = try? Data(contentsOf: url) else {
            return ClipboardHistoryBook()
        }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return (try? decoder.decode(ClipboardHistoryBook.self, from: data)) ?? ClipboardHistoryBook()
    }

    @discardableResult
    public func mutateChecked<T>(_ body: (inout ClipboardHistoryBook) throws -> T) throws -> T {
        let lockPath = url.path + ".lock"
        return try FileLock.withLock(path: lockPath) {
            var book = Self.decodeBook(from: url)
            let output = try body(&book)
            let encoder = JSONEncoder()
            encoder.outputFormatting = [.sortedKeys]
            encoder.dateEncodingStrategy = .iso8601
            let data = try encoder.encode(book)
            try Self.writePrivateAtomic(data, to: url)
            return output
        }
    }

    /// Écriture atomique strictement privée (`0o600` dès la création du fichier temporaire + `fsync` + `rename`).
    public static func writePrivateAtomic(_ data: Data, to destination: URL) throws {
        let directory = destination.deletingLastPathComponent()
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let tempName = ".\(destination.lastPathComponent).tmp-\(UUID().uuidString)"
        let tempURL = directory.appendingPathComponent(tempName)
        let fd = Darwin.open(tempURL.path, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW, mode_t(0o600))
        guard fd >= 0 else {
            throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno))
        }
        var fdOpen = true
        var committed = false
        defer {
            if fdOpen { _ = Darwin.close(fd) }
            if !committed {
                _ = Darwin.unlink(tempURL.path)
            }
        }
        try data.withUnsafeBytes { rawBuffer in
            guard let base = rawBuffer.baseAddress else { return }
            var written = 0
            while written < rawBuffer.count {
                let n = Darwin.write(fd, base.advanced(by: written), rawBuffer.count - written)
                if n < 0 {
                    if errno == EINTR { continue }
                    throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno))
                }
                written += n
            }
        }
        _ = Darwin.fchmod(fd, mode_t(0o600))
        if Darwin.fsync(fd) != 0 {
            throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno))
        }
        fdOpen = false
        if Darwin.close(fd) != 0 {
            throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno))
        }
        if Darwin.rename(tempURL.path, destination.path) != 0 {
            throw NSError(domain: NSPOSIXErrorDomain, code: Int(errno))
        }
        _ = Darwin.chmod(destination.path, mode_t(0o600))
        committed = true
    }
}

/// Surveillance légère du presse-papiers système (`NSPasteboard.general`, Spec 163).
/// Lorsque `clipboard.enabled == false` : 0 timer, 0 lecture pasteboard.
@MainActor
public final class ClipboardMonitor {
    public static let shared = ClipboardMonitor()

    private let store: ClipboardHistoryStore
    private let configLoader: () -> RoadieConfig
    private var timer: Timer?
    private var configObservers: [NSObjectProtocol] = []
    private var started = false
    private var lastChangeCount: Int
    var isTimerRunning: Bool { timer != nil }

    public init(
        store: ClipboardHistoryStore = ClipboardHistoryStore(),
        configLoader: @escaping () -> RoadieConfig = { ConfigReloadService.shared.currentConfig() }
    ) {
        self.store = store
        self.configLoader = configLoader
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    public func start() {
        guard !started else { return }
        started = true
        lastChangeCount = NSPasteboard.general.changeCount
        for name: Notification.Name in [.roadieConfigDidReload, .roadieSettingsDidChange] {
            configObservers.append(NotificationCenter.default.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor in self?.syncTimerForCurrentConfig() }
            })
        }
        syncTimerForCurrentConfig()
    }

    public func stop() {
        started = false
        configObservers.forEach { NotificationCenter.default.removeObserver($0) }
        configObservers.removeAll()
        stopTimer()
    }

    func syncTimerForCurrentConfig() {
        guard started else { return }
        let enabled = configLoader().clipboard.enabled
        guard enabled else {
            stopTimer()
            return
        }
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let created = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.pollOnce() }
        }
        created.tolerance = 0.25
        RunLoop.main.add(created, forMode: .common)
        timer = created
    }

    private func stopTimer() {
        timer?.invalidate()
        timer = nil
    }

    /// Lit le presse-papiers courant si son `changeCount` a évolué, applique le filtre de sécurité et enregistre.
    func pollOnce(now: Date = Date()) {
        let config = configLoader().clipboard
        guard config.enabled else {
            stopTimer()
            return
        }
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        let rawTypes = Set(pasteboard.types?.map(\.rawValue) ?? [])
        let sourceBundle = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let text = pasteboard.string(forType: .string)
        ingest(text: text, pasteboardTypes: rawTypes, sourceBundleID: sourceBundle, config: config, now: now)
    }

    /// Point d'entrée testable sans `NSPasteboard` : vérifie `ClipboardSecurityFilter` avant toute persistance.
    @discardableResult
    func ingest(
        text: String?,
        pasteboardTypes: Set<String>,
        sourceBundleID: String?,
        config: ClipboardConfig,
        now: Date = Date()
    ) -> Bool {
        guard config.enabled else { return false }
        guard !ClipboardSecurityFilter.shouldIgnore(
            text: text,
            pasteboardTypes: pasteboardTypes,
            sourceBundleID: sourceBundleID,
            excludedBundles: config.excludedBundles
        ), let text else {
            return false
        }
        do {
            _ = try store.mutateChecked { book in
                book.record(
                    text: text,
                    sourceBundleID: sourceBundleID,
                    now: now,
                    maxItems: config.maxItems,
                    retentionDays: config.retentionDays
                )
            }
            return true
        } catch {
            return false
        }
    }

    /// Lit le texte brut du presse-papiers système uniquement s'il ne porte aucun marqueur sensible
    /// (`ConcealedType`, `TransientType`, `AutoGeneratedType`, etc.).
    public static func readPlainTextIfSafe() -> String? {
        let pasteboard = NSPasteboard.general
        let rawTypes = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard !ClipboardSecurityFilter.hasForbiddenPasteboardType(rawTypes) else { return nil }
        return pasteboard.string(forType: .string)
    }

    /// Recopie une entrée dans `NSPasteboard.general` en marquant la nouvelle copie.
    @discardableResult
    public static func copyToPasteboard(_ text: String, transient: Bool = false) -> Bool {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let ok = pasteboard.setString(text, forType: .string)
        if transient {
            pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        }
        return ok
    }
}
