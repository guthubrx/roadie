    @Test func snippetExpansionIsSinglePassAndSupportsAllVariables() throws {
        var comps = DateComponents()
        comps.year = 2026
        comps.month = 11
        comps.day = 24
        comps.hour = 14
        comps.minute = 35
        comps.timeZone = TimeZone(identifier: "UTC")
        let utc = try #require(TimeZone(identifier: "UTC"))
        let date = try #require(Calendar(identifier: .gregorian).date(from: comps))

        // Le contenu du presse-papiers contenant `{date}` ne doit PAS être ré-étendu !
        let expanded = SnippetsService.expand(
            "Le {date} à {time} ({datetime}) : [{clipboard}] -> {cursor}fin",
            now: date,
            timeZone: utc,
            clipboardText: "littéral {date}"
        )
        #expect(expanded.text == "Le 2026-11-24 à 14:35 (2026-11-24 14:35) : [littéral {date}] -> fin")
        #expect(expanded.cursorOffsetFromEnd == 3) // "fin" = 3 caractères après {cursor}
    }

    @Test @MainActor func snippetTypingBufferAndAutoExpanderGating() {
        let items = [
            SnippetItem(keyword: ";sig", title: "Signature", body: "Cordialement"),
            SnippetItem(keyword: ";mail", title: "Email", body: "hello@example.org"),
        ]
        var buffer = SnippetTypingBuffer()
        var matched: SnippetItem?
        for ch in "bonjour ;sig " {
            matched = buffer.append(ch, items: items)
        }
        #expect(matched?.keyword == ";sig")

        // Sans frontière non-alphanumérique avant le mot-clé (ex: "abc;sig" ok car ';' non alphanum, "testmail" non)
        let alphaItems = [SnippetItem(keyword: "brb", title: "BRB", body: "Be right back")]
        buffer.reset()
        var falseMatch: SnippetItem?
        for ch in "abrb " {
            falseMatch = buffer.append(ch, items: alphaItems)
        }
        #expect(falseMatch == nil)

        buffer.reset()
        var trueMatch: SnippetItem?
        for ch in "brb " {
            trueMatch = buffer.append(ch, items: alphaItems)
        }
        #expect(trueMatch?.keyword == "brb")

        // Auto-expandeur strictement inactif quand auto_expand == false (défaut)
        var cfg = RoadieConfig()
        cfg.snippets.items = items
        cfg.snippets.autoExpand = false
        let expander = SnippetAutoExpander(configLoader: { cfg })
        defer { expander.stop() }
        expander.start()
        #expect(!expander.hasActiveKeyMonitor)
    }

