    // MARK: - Sécurité stricte presse-papiers & permissions 0o600

    @Test func securityFilterStrictlyRejectsSecretsTransientAndPasswordManagers() {
        let excluded = ClipboardConfig.defaultExcludedBundles
        let normalTypes: Set<String> = ["public.utf8-plain-text"]

        // Types interdits (casse quelconque) : JAMAIS enregistrés
        for forbidden in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword",
            "com.typeit4me.clipping",
            "de.petermaurer.TransientPasteboardType",
        ] {
            #expect(ClipboardSecurityFilter.shouldIgnore(
                text: "super-secret-password",
                pasteboardTypes: normalTypes.union([forbidden]),
                sourceBundleID: "com.apple.Notes",
                excludedBundles: excluded
            ))
        }

        // Gestionnaires de mots de passe exclus par défaut (KeePassXC, 1Password, Bitwarden, Keychain…)
        for bundle in ["org.keepassxc.keepassxc", "com.1password.1password", "com.bitwarden.desktop", "com.apple.keychainaccess"] {
            #expect(ClipboardSecurityFilter.shouldIgnore(
                text: "s3cr3t",
                pasteboardTypes: normalTypes,
                sourceBundleID: bundle,
                excludedBundles: excluded
            ))
        }

        // Vide / espaces seuls / blob > 64 Kio : ignorés
        #expect(ClipboardSecurityFilter.shouldIgnore(text: nil, pasteboardTypes: normalTypes, sourceBundleID: "com.apple.Notes", excludedBundles: excluded))
        #expect(ClipboardSecurityFilter.shouldIgnore(text: "   \n\t ", pasteboardTypes: normalTypes, sourceBundleID: "com.apple.Notes", excludedBundles: excluded))
        let huge = String(repeating: "a", count: ClipboardSecurityFilter.maxStoredTextUTF8Bytes + 1)
        #expect(ClipboardSecurityFilter.shouldIgnore(text: huge, pasteboardTypes: normalTypes, sourceBundleID: "com.apple.Notes", excludedBundles: excluded))

        // Texte ordinaire d'une application non exclue : accepté
        #expect(!ClipboardSecurityFilter.shouldIgnore(
            text: "Hello Roadie",
            pasteboardTypes: normalTypes,
            sourceBundleID: "com.apple.Notes",
            excludedBundles: excluded
        ))
    }

    @Test func clipboardStoreEnforces0600PermissionsAndBookLifecycle() throws {
        let dir = try tempDir("store")
        defer { try? FileManager.default.removeItem(at: dir) }
        let file = dir.appendingPathComponent("clipboard.json")
        let store = ClipboardHistoryStore(path: file.path)

        let t0 = Date(timeIntervalSince1970: 1_700_000_000)
        try store.mutateChecked { book in
            _ = book.record(text: "premier", sourceBundleID: "com.apple.Notes", now: t0, maxItems: 3, retentionDays: 7)
            _ = book.record(text: "deuxième", sourceBundleID: "com.apple.Terminal", now: t0.addingTimeInterval(10), maxItems: 3, retentionDays: 7)
            _ = book.record(text: "troisième", sourceBundleID: "com.apple.Safari", now: t0.addingTimeInterval(20), maxItems: 3, retentionDays: 7)
        }

        // Permissions strictement 0o600 sur le fichier créé
        let attrs = try FileManager.default.attributesOfItem(atPath: file.path)
        let posix = (attrs[.posixPermissions] as? NSNumber)?.intValue
        #expect(posix == 0o600)

        // Épingler le plus ancien ("premier"), puis ajouter "quatrième" -> "deuxième" est évincé, "premier" reste !
        try store.mutateChecked { book in
            let firstID = try #require(book.entries.first(where: { $0.text == "premier" })?.id)
            let pinned = book.togglePin(idOrPrefix: String(firstID.prefix(8)))
            #expect(pinned?.pinned == true)
            _ = book.record(text: "quatrième", sourceBundleID: "com.apple.Notes", now: t0.addingTimeInterval(30), maxItems: 3, retentionDays: 7)
        }
        let afterCap = store.load()
        #expect(afterCap.entries.count == 3)
        #expect(afterCap.entries.contains { $0.text == "premier" && $0.pinned })
        #expect(!afterCap.entries.contains { $0.text == "deuxième" })

        // Déduplication : re-copier "premier" le remonte en tête et conserve son état épinglé
        try store.mutateChecked { book in
            _ = book.record(text: "premier", sourceBundleID: "com.apple.Notes", now: t0.addingTimeInterval(40), maxItems: 3, retentionDays: 7)
        }
        let afterDedup = store.load()
        #expect(afterDedup.entries.first?.text == "premier")
        #expect(afterDedup.entries.first?.pinned == true)
        #expect(afterDedup.entries.count == 3)

        // Rétention : 10 jours plus tard (retention = 7), les non-épinglés expirent mais l'épinglé survit
        try store.mutateChecked { book in
            book.prune(now: t0.addingTimeInterval(10 * 86_400), maxItems: 3, retentionDays: 7)
        }
        let afterPrune = store.load()
        #expect(afterPrune.entries.map(\.text) == ["premier"])

        // Clear sans --all préserve l'épinglé ; clear(includePinned: true) vide tout
        let removedNormal = try store.mutateChecked { $0.clear(includePinned: false) }
        #expect(removedNormal == 0)
        let removedAll = try store.mutateChecked { $0.clear(includePinned: true) }
        #expect(removedAll == 1)
        #expect(store.load().entries.isEmpty)
    }

    @Test @MainActor func clipboardMonitorDisablesTimerWhenOffAndRejectsSecretsOnIngest() throws {
        let dir = try tempDir("monitor")
        defer { try? FileManager.default.removeItem(at: dir) }
        let store = ClipboardHistoryStore(path: dir.appendingPathComponent("clipboard.json").path)
        var cfg = RoadieConfig()
        cfg.clipboard.enabled = false

        let monitor = ClipboardMonitor(store: store, configLoader: { cfg })
        defer { monitor.stop() }
        monitor.start()
        #expect(!monitor.isTimerRunning)

        cfg.clipboard.enabled = true
        monitor.syncTimerForCurrentConfig()
        #expect(monitor.isTimerRunning)

        // Un mot de passe KeePassXC ou ConcealedType n'est jamais persisté
        #expect(!monitor.ingest(
            text: "secret123",
            pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"],
            sourceBundleID: "com.apple.Notes",
            config: cfg.clipboard
        ))
        #expect(!monitor.ingest(
            text: "keepass-secret",
            pasteboardTypes: ["public.utf8-plain-text"],
            sourceBundleID: "org.keepassxc.keepassxc",
            config: cfg.clipboard
        ))
        #expect(store.load().entries.isEmpty)

        // Une copie normale est persistée
        #expect(monitor.ingest(
            text: "Note de réunion",
            pasteboardTypes: ["public.utf8-plain-text"],
            sourceBundleID: "com.apple.Notes",
            config: cfg.clipboard
        ))
        #expect(store.load().entries.map(\.text) == ["Note de réunion"])

        cfg.clipboard.enabled = false
        monitor.syncTimerForCurrentConfig()
        #expect(!monitor.isTimerRunning)
    }

